def reading_for_weight(total, classification):
    exact = EXACT_READINGS.get(total)
    band_index = sum(total > limit for limit in (31, 43, 56))
    title, poem, explanation, paragraphs = exact or BAND_READINGS[band_index]
    return {
        "title": title,
        "poem": poem.splitlines(),
        "poem_label": "Thơ Hán–Việt do anh Sơn cung cấp" if exact else f"Thơ diễn ý mới · {classification}",
        "explanation": explanation,
        "sections": [{"heading": heading, "text": paragraph}
                     for heading, paragraph in zip(HEADINGS, paragraphs)],
    }
